/**
 * Editable text -> actual rendering consumers. This is a layout catalogue, not validation.
 * `bounded` uses either a measured structural budget or an explicitly marked
 * `basis: 'reference'` estimate of the approved default composition. A reference
 * is not a clipping limit. `flowing` must not acquire a finite total-length cap.
 *
 * Selectors name the smallest existing text host. A host may also contain other text,
 * icons or all three xbtn faces: probes must preserve those siblings. Dynamic topic
 * and collection consumers intentionally cover every possible slot, not saved IDs.
 * `boundary` is a closest-ancestor selector, except html/body which denote the viewport.
 * `all` includes the shared 404 document; Worker-only geo selectors have no Astro match.
 */

