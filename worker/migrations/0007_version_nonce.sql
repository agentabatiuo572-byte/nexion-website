-- 把本次发布的一次性口令**也**记在版本行上(2026-09-01 第六轮,192 格转移表抓出)。
--
-- 为什么:上线核验要拿印记里的口令与「本次发布的口令」比对,而口令原先只存在 publish_lock 里。
-- 可**终态回报会删锁** —— 于是「回报送到了但响应在回程丢了、执行器重发」这个真实形态里,
-- 重放走到核验时锁已经不在,口令读不到,核验必然判失败。
-- 我为这个场景写的回归测试当时通过了,是因为它**保留了锁**,不忠实于真实状态;
-- 192 格穷举表把这处失真抓了出来(格:步=swap × 已记录=ok × 上报=ok × 锁=none)。
--
-- 口令属于「这一次发布」,而发布的载体是版本行,不是那把会被释放的锁 —— 放对地方它就不会消失。
